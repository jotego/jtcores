from pathlib import Path

image = bytearray(1 << 20)
code = bytearray()
fixups = []


def emit(*values):
    code.extend(values)


def equal():
    emit(0x74, 3, 0xe9, 0, 0)
    fixups.append(len(code) - 2)


emit(0xfa, 0x31, 0xc0, 0x8e, 0xd8, 0x8e, 0xd0, 0x8e, 0xc0, 0xbc, 0, 0x70, 0xfc)
emit(0xb8, 0x34, 0x12, 0xa3, 0, 0x20, 0x8b, 0x1e, 0, 0x20, 0x81, 0xfb, 0x34, 0x12)
equal()
emit(0xb8, 0xcd, 0xab, 0xa3, 1, 0x20, 0xa1, 1, 0x20, 0x3d, 0xcd, 0xab)
equal()
emit(0xc6, 0x06, 3, 0x20, 0x5a, 0xa0, 4, 0x20, 0x3c, 0xa5)
equal()
emit(0xb8, 0, 0, 0xb9, 3, 0, 0x0f, 0x14, 0xc0, 0xa3, 0x10, 0x20, 0x3d, 8, 0)
equal()
emit(0x0f, 0x1c, 0xc0, 7, 0xa3, 0x12, 0x20, 0x3d, 0x88, 0)
equal()
emit(0xb8, 0x34, 0x12, 0xe7, 0x80, 0xe5, 0x80, 0x3d, 0xc3, 0x5a)
equal()
emit(0xcd, 0x40, 0x83, 0x3e, 8, 0x60, 1)
equal()
emit(0xc7, 0x06, 2, 0x60, 1, 0, 0xfb, 0xf4, 0x90, 0x9c, 0x58, 0x25, 0, 2, 0x3d, 0, 2)
equal()
emit(0xfa, 0x83, 0x3e, 4, 0x60, 1)
equal()
emit(0xc7, 0x06, 2, 0x60, 2, 0, 0xf4, 0x90, 0x83, 0x3e, 6, 0x60, 1)
equal()
emit(0xc7, 0x06, 0, 0x60, 0x55, 0xaa, 0xfa, 0xf4, 0xeb, 0xfd)
failure = len(code)
emit(0xc7, 0x06, 0, 0x60, 0xad, 0xde, 0xfa, 0xf4, 0xeb, 0xfd)
for offset in fixups:
    code[offset:offset + 2] = (failure - offset - 2).to_bytes(2, 'little', signed=True)
image[0x100:0x100 + len(code)] = code
image[0xffff0:0xffff5] = bytes((0xea, 0, 1, 0, 0))
image[0x2004] = 0xa5
for vector, address, flag in ((0x32, 0x400, 0x6004), (2, 0x420, 0x6006), (0x40, 0x440, 0x6008)):
    image[vector * 4:vector * 4 + 4] = address.to_bytes(2, 'little') + b'\x00\x00'
    image[address:address + 5] = bytes((0xff, 0x06, flag & 255, flag >> 8, 0xcf))
Path(__file__).with_name('program.bin').write_bytes(image)
