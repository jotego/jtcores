def tile_to_2bpp(pens):
    """Encode 8x8 array of pen values (0-3) to GnG 2bpp char ROM format.

    MAME charlayout: planes {4,0}, xoffset {0,1,2,3,8,9,10,11}.
    Each row = 2 bytes. Each byte packs plane1 in high nibble,
    plane0 in low nibble, for 4 pixels. Leftmost pixel at MSB of nibble.

    The MRA map="12" interleave will later split these nibbles into
    separate bytes in the 16-bit SDRAM word for the FPGA. We just need
    to produce the correct MAME-format ROM bytes here.
    """
    data = bytearray(16)
    for y in range(8):
        row = pens[y]
        p0 = [(row[x] >> 0) & 1 for x in range(8)]
        p1 = [(row[x] >> 1) & 1 for x in range(8)]
        # GnG FPGA char module reads D[15:12] as plane0, D[11:8] as plane1
        # for pixels 0-3, and D[7:4]/D[3:0] for pixels 4-7.
        # After MRA map="12" + jtutil byte-swap = identity, so ROM byte
        # layout must match: high nibble = plane0, low nibble = plane1.
        p0_left = (p0[0]<<3) | (p0[1]<<2) | (p0[2]<<1) | p0[3]
        p1_left = (p1[0]<<3) | (p1[1]<<2) | (p1[2]<<1) | p1[3]
        p0_right = (p0[4]<<3) | (p0[5]<<2) | (p0[6]<<1) | p0[7]
        p1_right = (p1[4]<<3) | (p1[5]<<2) | (p1[6]<<1) | p1[7]
        data[y*2]   = (p0_left << 4) | p1_left
        data[y*2+1] = (p0_right << 4) | p1_right
    return bytes(data)


def glyph_to_2bpp(rows):
    """Convert font glyph rows to 2bpp with drop-shadow.

    pen 0=bg, pen 1=body, pen 2=shadow (1px down-right).
    """
    body = [[(rows[y] >> (7-x)) & 1 for x in range(8)] for y in range(8)]
    pens = [[0]*8 for _ in range(8)]
    for y in range(8):
        for x in range(8):
            if body[y][x]:
                pens[y][x] = 1
            elif y > 0 and x > 0 and body[y-1][x-1]:
                pens[y][x] = 2
    return tile_to_2bpp(pens)


