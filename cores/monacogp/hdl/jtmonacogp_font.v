// 5x7 character generator for the development views (not original artwork).
module jtmonacogp_font(
    input      [7:0] ch,
    input      [2:0] row,   // 0..6, top to bottom
    input      [2:0] col,   // 0..4, left to right
    output           pix
);
    reg [34:0] g;
    always @* begin
        case (ch)
            "("  : g=35'b00010_00100_01000_01000_01000_00100_00010;
            ")"  : g=35'b01000_00100_00010_00010_00010_00100_01000;
            ","  : g=35'b00000_00000_00000_00000_01100_00100_01000;
            "-"  : g=35'b00000_00000_00000_11111_00000_00000_00000;
            "."  : g=35'b00000_00000_00000_00000_00000_01100_01100;
            "/"  : g=35'b00000_00001_00010_00100_01000_10000_00000;
            "0"  : g=35'b01110_10001_10011_10101_11001_10001_01110;
            "1"  : g=35'b00100_01100_00100_00100_00100_00100_01110;
            "2"  : g=35'b01110_10001_00001_00010_00100_01000_11111;
            "3"  : g=35'b11111_00010_00100_00010_00001_10001_01110;
            "4"  : g=35'b00010_00110_01010_10010_11111_00010_00010;
            "5"  : g=35'b11111_10000_11110_00001_00001_10001_01110;
            "6"  : g=35'b00110_01000_10000_11110_10001_10001_01110;
            "7"  : g=35'b11111_00001_00010_00100_01000_01000_01000;
            "8"  : g=35'b01110_10001_10001_01110_10001_10001_01110;
            "9"  : g=35'b01110_10001_10001_01111_00001_00010_01100;
            ":"  : g=35'b00000_00100_00100_00000_00100_00100_00000;
            "="  : g=35'b00000_00000_11111_00000_11111_00000_00000;
            "A"  : g=35'b01110_10001_10001_11111_10001_10001_10001;
            "B"  : g=35'b11110_10001_10001_11110_10001_10001_11110;
            "C"  : g=35'b01111_10000_10000_10000_10000_10000_01111;
            "D"  : g=35'b11110_10001_10001_10001_10001_10001_11110;
            "E"  : g=35'b11111_10000_10000_11110_10000_10000_11111;
            "F"  : g=35'b11111_10000_10000_11110_10000_10000_10000;
            "G"  : g=35'b01111_10000_10000_10111_10001_10001_01111;
            "H"  : g=35'b10001_10001_10001_11111_10001_10001_10001;
            "I"  : g=35'b11111_00100_00100_00100_00100_00100_11111;
            "J"  : g=35'b00111_00010_00010_00010_00010_10010_01100;
            "K"  : g=35'b10001_10010_10100_11000_10100_10010_10001;
            "L"  : g=35'b10000_10000_10000_10000_10000_10000_11111;
            "M"  : g=35'b10001_11011_10101_10101_10001_10001_10001;
            "N"  : g=35'b10001_11001_11001_10101_10011_10011_10001;
            "O"  : g=35'b01110_10001_10001_10001_10001_10001_01110;
            "P"  : g=35'b11110_10001_10001_11110_10000_10000_10000;
            "Q"  : g=35'b01110_10001_10001_10001_10101_10010_01101;
            "R"  : g=35'b11110_10001_10001_11110_10100_10010_10001;
            "S"  : g=35'b01111_10000_10000_01110_00001_00001_11110;
            "T"  : g=35'b11111_00100_00100_00100_00100_00100_00100;
            "U"  : g=35'b10001_10001_10001_10001_10001_10001_01110;
            "V"  : g=35'b10001_10001_10001_10001_10001_01010_00100;
            "W"  : g=35'b10001_10001_10001_10101_10101_10101_01010;
            "X"  : g=35'b10001_10001_01010_00100_01010_10001_10001;
            "Y"  : g=35'b10001_10001_01010_00100_00100_00100_00100;
            "Z"  : g=35'b11111_00001_00010_00100_01000_10000_11111;

            default: g=35'd0;
        endcase
    end
    // Bit 34 is row 0, column 0.
    wire [5:0] idx = 6'd34 - {3'd0,row}*6'd5 - {3'd0,col};
    assign pix = row < 3'd7 && col < 3'd5 && g[idx];
endmodule
